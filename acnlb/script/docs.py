def examples(proj=None):
    """[{id, title, description, code}] with {{building}} {{room}} {{villager}} {{outfit}} filled from the project"""
    proj = proj or {}
    b = (proj.get("buildings") or [{}])[0].get("id", "my_building")
    v = next((x for x in proj.get("villagers", []) if x.get("outfits")), None)
    vid = v["id"] if v else "my_villager"
    oid = v["outfits"][0]["id"] if v else "my_outfit"
    out = []
    d = os.path.join(HERE, "examples")
    for f in sorted(os.listdir(d)):
        if not f.endswith(".py"):
            continue
        code = open(os.path.join(d, f), encoding="utf-8").read()
        for k, val in (("building", b), ("villager", vid), ("outfit", oid)):
            code = code.replace("{{%s}}" % k, val)
        doc = code.split('"""')[1].strip() if code.startswith('"""') else ""
        title = doc.split(".")[0].split(":")[0].strip() or f
        out.append(dict(id=f[:-3], title=title, description=doc, code=code))
    return out
